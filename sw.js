self.addEventListener("install", function (event) {
  // cache: "reload" skips the browser's own HTTP cache, so an update never
  // stores a stale copy of a file that changed.
  event.waitUntil(caches.open(CACHE).then(function (cache) {
    return cache.addAll(FILES.map(function (url) { return new Request(url, { cache: "reload" }); }));
  }));
});

self.addEventListener("activate", function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) { return k.indexOf("tendril-") === 0 && k !== CACHE; })
        .map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

// Cache first: the app never needs the network once installed.
self.addEventListener("fetch", function (event) {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(function (hit) {
      return hit || fetch(req).catch(function () {
        if (req.mode === "navigate") return caches.match("./index.html");
        return Response.error();
      });
    })
  );
});

// The page asks the waiting worker to take over when the person taps "Update".
self.addEventListener("message", function (event) {
  if (event.data === "skip-waiting") self.skipWaiting();
});
